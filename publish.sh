#!/bin/sh
# publish.sh: rebuild the home page, render every handout to docs/, then
# commit and push so GitHub Pages republishes https://toetskoenyn.github.io/.
#
#   ./publish.sh              do everything
#   ./publish.sh --no-push    rebuild and render only; commit and push nothing
#
# A handout is any .qmd in this folder other than index.qmd. index.qmd is
# generated: don't edit it by hand, edit the handouts' front matter instead.
set -eu
cd "$(dirname "$0")"

push=1
[ "${1:-}" = "--no-push" ] && push=0

site=https://toetskoenyn.github.io/

# ---- 1. Stop early if the extension or config has uncommitted changes -------
# The rendered pages depend on them, so publishing pages without them would
# leave the repository out of step with the site.
if [ "$push" = 1 ]; then
  pending=$(git status --porcelain -- _extensions _quarto.yml _environment _design publish.sh)
  if [ -n "$pending" ]; then
    echo "Commit these first; the rendered pages depend on them:" >&2
    echo "$pending" >&2
    exit 1
  fi
  branch=$(git branch --show-current)
  if [ "$branch" != main ]; then
    echo "On branch '$branch'; publish from main." >&2
    exit 1
  fi
fi

# ---- 2. Rebuild index.qmd from the handouts' front matter -------------------
python3 - <<'PY'
import datetime, glob, re

def front_matter(path):
    text = open(path, encoding="utf-8").read()
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    meta = {}
    for line in (m.group(1).splitlines() if m else []):
        k = re.match(r'([A-Za-z_-]+):\s*"?(.*?)"?\s*$', line)
        if k:
            meta[k.group(1)] = k.group(2)
    return meta

items = []
for path in sorted(glob.glob("*.qmd")):
    if path == "index.qmd":
        continue
    meta = front_matter(path)
    name = path[:-4]
    title = meta.get("title", name)
    subtitle = meta.get("subtitle")
    items.append((meta.get("date", ""), title, subtitle, name))

# Newest first, then by title; undated handouts last.
dated = sorted((i for i in items if i[0]), key=lambda i: (i[0], i[1]), reverse=True)
undated = sorted((i for i in items if not i[0]), key=lambda i: i[1])
items = dated + undated

lines = [
    "---",
    'title: "Handouts"',
    'subtitle: "Typeset with Quarto and Typst"',
    f'date: "{datetime.date.today().isoformat()}"',
    'running: "Handouts"',
    "---",
    "",
    "<!-- Generated by publish.sh from each handout's front matter. Don't edit by hand. -->",
    "",
    "Each handout is available as a web page and as an A4 PDF.",
    "",
]
for date, title, subtitle, name in items:
    text = f"{title}: {subtitle}" if subtitle else title
    lines.append(f"- [{text}]({name}.html) · [PDF]({name}.pdf)")
if not items:
    lines.append("No handouts yet.")

new = "\n".join(lines) + "\n"
try:
    old = open("index.qmd", encoding="utf-8").read()
except FileNotFoundError:
    old = ""
# Keep the date unchanged unless the list itself changed, so an unchanged
# site doesn't produce a commit.
strip = lambda s: re.sub(r'^date: ".*"$', "", s, flags=re.M)
if strip(old) != strip(new):
    open("index.qmd", "w", encoding="utf-8").write(new)
    print(f"index.qmd: {len(items)} handout(s) listed")
else:
    print("index.qmd: unchanged")
PY

# ---- 3. Render, then drop outputs whose handout is gone ---------------------
quarto render

for out in docs/*.html docs/*.pdf; do
  [ -e "$out" ] || continue
  name=$(basename "$out"); name=${name%.*}
  if [ ! -f "$name.qmd" ]; then
    echo "Removing $out (no $name.qmd)"
    rm "$out"
  fi
done

if [ "$push" = 0 ]; then
  echo "Rendered to docs/. Not committed or pushed (--no-push)."
  exit 0
fi

# ---- 4. Commit the handouts and the site -----------------------------------
# Handouts and their .bib files in this folder only (added, changed or
# deleted), the images they use, and the rendered site. Never _sources/ or
# editor files.
git add -A -- docs ':(glob)*.qmd' ':(glob)*.bib'
[ -d images ] || git ls-files --error-unmatch images >/dev/null 2>&1 && git add -A -- images

if git diff --cached --quiet; then
  echo "Nothing changed; the site is up to date: $site"
  exit 0
fi

# A stamp that changes with every publish, so step 5 can tell when GitHub
# serves this version.
stamp="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "$stamp" > docs/build.txt
git add docs/build.txt

summary=$(git diff --cached --name-status -- '*.qmd' | grep -v 'index.qmd' | awk '
  $1 == "A" { sub(/\.qmd$/, "", $2); a = a (a ? ", " : "") $2 }
  $1 == "M" { sub(/\.qmd$/, "", $2); m = m (m ? ", " : "") $2 }
  $1 == "D" { sub(/\.qmd$/, "", $2); d = d (d ? ", " : "") $2 }
  END {
    if (a) print "Add: " a
    if (m) print "Update: " m
    if (d) print "Remove: " d
  }')
[ -n "$summary" ] || summary="Re-render the site"

git commit -q -m "Publish handouts" -m "$summary"
echo "Committed: $(git log --oneline -1)"

# ---- 5. Push and wait for GitHub Pages --------------------------------------
git push -q origin main
commit=$(git rev-parse --short HEAD)
echo "Pushed $commit. Waiting for GitHub Pages to republish..."

i=0
while [ $i -lt 40 ]; do
  got=$(curl -s "${site}build.txt?nocache=$(date +%s)" | tr -d '\n')
  if [ "$got" = "$stamp" ]; then
    echo "Live: $site"
    exit 0
  fi
  i=$((i + 1))
  sleep 15
done
echo "Pushed, but the site hasn't updated after 10 minutes. Check the Pages build:" >&2
echo "  https://github.com/toetskoenyn/toetskoenyn.github.io/actions" >&2
exit 1
